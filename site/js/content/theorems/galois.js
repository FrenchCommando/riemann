// Roots of x^5 − 4x + 2 by Durand–Kerner iteration, plotted in the complex plane.
const cmul = ([a, b], [c, d]) => [a * c - b * d, a * d + b * c];
const cdiv = ([a, b], [c, d]) => { const n = c * c + d * d; return [(a * c + b * d) / n, (b * c - a * d) / n]; };
const f = (z) => { const z2 = cmul(z, z), z4 = cmul(z2, z2), z5 = cmul(z4, z); return [z5[0] - 4 * z[0] + 2, z5[1] - 4 * z[1]]; };
let zs = Array.from({ length: 5 }, (_, k) => [Math.cos(0.4 + 1.25 * k) * 1.3, Math.sin(0.4 + 1.25 * k) * 1.3]);
for (let it = 0; it < 200; it++) {
  zs = zs.map((z, i) => {
    let den = [1, 0];
    zs.forEach((w, j) => { if (j !== i) den = cmul(den, [z[0] - w[0], z[1] - w[1]]); });
    const step = cdiv(f(z), den);
    return [z[0] - step[0], z[1] - step[1]];
  });
}
const real = zs.filter(([, b]) => Math.abs(b) < 1e-9).map(([a]) => a).sort((a, b) => a - b);
const [cplx] = zs.filter(([, b]) => b > 1e-9);
const U = 62;
