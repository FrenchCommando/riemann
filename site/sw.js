const CACHE = `riemann-${VERSION}`;

async function precache() {
  const c = await caches.open(CACHE);
  await c.add(new Request('./', { cache: 'no-cache' }));
  // One file failing must not fail the install: it gets cached on first use instead.
  await Promise.allSettled(FILES.map((f) => c.add(new Request(f, { cache: 'no-cache' }))));
}

self.addEventListener('install', (ev) => {
  ev.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (ev) => {
  ev.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

async function fromNetwork(req) {
  const res = await fetch(req);
  if (res.ok) {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy));
  }
  return res;
}

self.addEventListener('fetch', (ev) => {
  const req = ev.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (url.pathname.startsWith('/vendor/')) {
    ev.respondWith(caches.match(req).then((hit) => hit ?? fromNetwork(req)));
    return;
  }
  ev.respondWith(fromNetwork(req).catch(async () =>
    (await caches.match(req)) ?? (req.mode === 'navigate' ? caches.match('index.html') : Response.error())));
});
