// Offline support for the installed app.
//
// Cache first. Install saves every file in FILES, so the cache always holds one
// complete, consistent copy of the site and the app opens instantly with or
// without a network. Network-first would hang on a network that is connected
// but not working (dead Wi-Fi, captive portal, one bar of signal): the request
// neither answers nor fails, so the cached copy is never reached.
//
// Updates: VERSION is a hash of the whole site, so any deployed change changes
// this script. The browser checks it whenever the app opens, installs the new
// worker, which saves a complete copy into a new cache, and the old cache is
// deleted on activation. A deploy therefore shows from the next open.
//
// Anything not saved at install (the plain pages under /p/, preview images)
// goes to the network, given up after NETWORK_TIMEOUT ms; a page then falls
// back to the app.

