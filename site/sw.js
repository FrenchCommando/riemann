const CACHE = `riemann-${VERSION}`;

async function precache() {
  const c = await caches.open(CACHE);
  await c.add(new Request('./', { cache: 'no-cache' }));
  // One file failing must not fail the install: it gets cached on first use instead.
  await Promise.allSettled(FILES.map((f) => c.add(new Request(f, { cache: 'no-cache' }))));
}

self.addEventListener('install', (ev) => {
  ev.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (ev) => {
  ev.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

async function fromNetwork(req) {
  const res = await fetch(req);
  if (res.ok) {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy));
  }
  return res;
}

const NETWORK_TIMEOUT = 4000;

function withTimeout(promise, ms) {
  return Promise.race([promise, new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms))]);
}

async function respond(req) {
  const hit = await caches.match(req);
  if (hit) return hit;
  try {
    return await withTimeout(fromNetwork(req), NETWORK_TIMEOUT);
  } catch {
    return (req.mode === 'navigate' && (await caches.match('./'))) || Response.error();
  }
}

self.addEventListener('fetch', (ev) => {
  const req = ev.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  ev.respondWith(respond(req));
});
