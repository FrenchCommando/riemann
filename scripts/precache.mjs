// Writes into sw.js, between the FILES markers, the list of every file under
// site/ and a VERSION hashed from their names and contents. Any change to the
// site therefore changes sw.js, which makes browsers install a new worker that
// saves a fresh copy of the whole site.
// The test suite fails when the block is stale; run `npm run precache` to fix it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = fileURLToPath(new URL('../site/', import.meta.url));
const swPath = `${site}sw.js`;
export const BEGIN = '// BEGIN FILES (generated by npm run precache)';
export const END = '// END FILES';

// The pages for crawlers and link previews (scripts/pages.mjs, scripts/cards.mjs)
// are not part of the app, so they are not saved for offline use.
const notApp = /^(sw\.js|p\/.*|og\/.*|sitemap\.xml|robots\.txt)$/;

export function siteFiles() {
  return readdirSync(site, { recursive: true, withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => relative(site, `${d.parentPath}${sep}${d.name}`).split(sep).join('/'))
    .filter((f) => !notApp.test(f))
    .sort();
}

// Line endings are normalised so a Windows (CRLF) checkout hashes the same as CI.
export function version(files) {
  const h = createHash('sha256');
  for (const f of files) {
    const bytes = readFileSync(`${site}${f}`);
    h.update(`${f}\0`).update(/\.(woff2|png)$/.test(f) ? bytes : bytes.toString('utf8').replace(/\r\n/g, '\n')).update('\0');
  }
  return h.digest('hex').slice(0, 12);
}

export function render(files) {
  return `${BEGIN}\nconst VERSION = '${version(files)}';\nconst FILES = [\n${files.map((f) => `  '${f}',`).join('\n')}\n];\n${END}`;
}

export function currentBlock(sw = readFileSync(swPath, 'utf8')) {
  const a = sw.indexOf(BEGIN), b = sw.indexOf(END);
  if (a < 0 || b < 0) throw new Error('sw.js: FILES markers not found');
  return { sw, a, b: b + END.length, block: sw.slice(a, b + END.length) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { sw, a, b } = currentBlock();
  const files = siteFiles();
  writeFileSync(swPath, sw.slice(0, a) + render(files) + sw.slice(b));
  console.log(`sw.js: ${files.length} files`);
}
